import os

def generate_markdown_report(audit_res, model_res, adv_res, out_md, dataset_name):
    lines = []
    lines.append(f"# ResearchBench Report: {dataset_name}")
    lines.append("")
    lines.append("## 1. Executive Summary")
    lines.append("This report was automatically generated by ResearchBench.")
    if adv_res and "insights" in adv_res:
        lines.append("")
        for insight in adv_res["insights"]:
            lines.append(f"- **{insight['category']}**: {insight['insight']}")
            
    lines.append("")
    lines.append("## 2. Dataset Profile")
    health = audit_res.get("health", {}).get("profile", {})
    lines.append(f"- Rows: {health.get('num_rows', 'N/A')}")
    lines.append(f"- Columns: {health.get('num_cols', 'N/A')}")
    lines.append(f"- Missing Data: {health.get('missing_percentage', 0):.2f}%")
    
    if "outlier_fraction" in audit_res:
        lines.append(f"- Anomalies: {audit_res['outlier_fraction']*100:.1f}%")
        
    lines.append("")
    lines.append("## 3. Model Performance")
    for name, m_data in model_res.items():
        lines.append(f"### {name}")
        if "metrics" in m_data:
            for k, v in m_data["metrics"].items():
                if isinstance(v, float):
                    lines.append(f"- **{k}**: {v:.4f}")
                else:
                    lines.append(f"- **{k}**: {v}")
        lines.append("")
        
    try:
        with open(out_md, "w", encoding="utf-8") as f:
            f.write("\n".join(lines))
        return True
    except Exception:
        return False